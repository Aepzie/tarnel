// Regenerates the Android logo assets from the desktop's single source of truth,
// src/shared/brand-mark.ts (cap + body paths, accent, tile colour):
//
//   app/src/main/res/drawable/ic_vela_mark.xml          launcher foreground + splash (accent cap, white body)
//   app/src/main/res/drawable/ic_vela_mono.xml          themed-icon monochrome layer (both pieces, one colour)
//   app/src/main/res/drawable/ic_launcher_background.xml  dark tile with the accent glow
//   app/src/main/java/org/velabrowser/vela/ui/brand/BrandMark.kt  path data for the in-app Compose logo
//
// No dependencies:  node android/scripts/brand-mark.mjs   (or ./gradlew :app:syncBrandMark)
// BrandMarkSyncTest fails when the generated files drift from brand-mark.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const androidDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(androidDir, '..', 'src', 'shared', 'brand-mark.ts'), 'utf8');

function constant(name) {
  const match = source.match(new RegExp(`export const ${name}\\s*=\\s*'([^']+)'`));
  if (!match) throw new Error(`brand-mark.ts: ${name} not found`);
  return match[1];
}
function number(name) {
  const match = source.match(new RegExp(`const ${name}\\s*=\\s*([0-9.]+)`));
  if (!match) throw new Error(`brand-mark.ts: ${name} not found`);
  return Number(match[1]);
}

const cap = constant('BRAND_CAP_PATH');
const body = constant('BRAND_BODY_PATH');
const viewBox = constant('BRAND_GLYPH_VIEWBOX').split(/\s+/).map(Number);
const accent = constant('BRAND_ACCENT');
const ink = constant('BRAND_INK');
const tile = constant('BRAND_TILE');
const glyphScale = number('GLYPH_SCALE');

const argb = (hex, alpha = 'FF') => `#${alpha}${hex.replace('#', '').toUpperCase()}`;
const round = (n) => Number(n.toFixed(5));

// Adaptive icons: 108dp canvas, the launcher mask shows the centre 72dp. The desktop tile (1024) maps onto
// those 72dp, and the glyph keeps the desktop's scale inside the tile, so both icons look the same.
const scale = round((72 / 1024) * glyphScale);
const header = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/scripts/brand-mark.mjs from src/shared/brand-mark.ts. Do not edit. -->\n';
const group = (paths) =>
  [
    '    <group',
    '        android:pivotX="512"',
    '        android:pivotY="512"',
    `        android:scaleX="${scale}"`,
    `        android:scaleY="${scale}"`,
    '        android:translateX="-458"',
    '        android:translateY="-458">',
    ...paths.map(([d, color]) => `        <path\n            android:fillColor="${color}"\n            android:pathData="${d}" />`),
    '    </group>',
  ].join('\n');
const vector = (inner) =>
  `${header}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${inner}
</vector>
`;

const res = join(androidDir, 'app', 'src', 'main', 'res', 'drawable');
writeFileSync(join(res, 'ic_vela_mark.xml'), vector(group([[body, argb(ink)], [cap, argb(accent)]])));
writeFileSync(join(res, 'ic_vela_mono.xml'), vector(group([[body, '#FFFFFFFF'], [cap, '#FFFFFFFF']])));
writeFileSync(
  join(res, 'ic_launcher_background.xml'),
  `${header}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="${argb(tile)}"
        android:pathData="M0,0h108v108h-108z" />
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:centerX="54"
                android:centerY="${round(18 + 72 * 0.3)}"
                android:gradientRadius="${round(72 * 0.72)}"
                android:type="radial">
                <item android:color="${argb(accent, '3D')}" android:offset="0" />
                <item android:color="${argb(accent, '00')}" android:offset="1" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
`,
);

const kotlin = `package org.velabrowser.vela.ui.brand

// Generated by android/scripts/brand-mark.mjs from src/shared/brand-mark.ts. Do not edit.

/** The Vela mark: an accent cap above a sail body, in a 1024 coordinate box. */
object BrandMark {
    const val CAP_PATH = "${cap}"
    const val BODY_PATH = "${body}"
    const val VIEWBOX_X = ${viewBox[0]}f
    const val VIEWBOX_Y = ${viewBox[1]}f
    const val VIEWBOX_SIZE = ${viewBox[2]}f
    const val ACCENT = 0x${argb(accent).slice(1)}
    const val INK = 0x${argb(ink).slice(1)}
    const val TILE = 0x${argb(tile).slice(1)}
}
`;
writeFileSync(join(androidDir, 'app', 'src', 'main', 'java', 'org', 'velabrowser', 'vela', 'ui', 'brand', 'BrandMark.kt'), kotlin);
console.log('brand mark synced');
